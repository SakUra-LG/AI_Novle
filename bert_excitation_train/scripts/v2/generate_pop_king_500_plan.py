def _unique_text(values: list[Any], separator: str = "；") -> str:
    out: list[str] = []
    for value in values:
        text = str(value or "").strip()
        if text and text not in out:
            out.append(text)
    return separator.join(out)


def build() -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    """Expand 100 curated kernels into exactly 250 two-chapter events.

    Five adjacent two-chapter events form one ten-chapter macro group.  This
    preserves long-range continuity without treating a five-chapter kernel as
    only one payoff event.
    """
    kernels, kernel_cards, bible = _build_five_chapter_kernels()
    events: list[dict[str, Any]] = []
    cards: list[dict[str, Any]] = []
    macro_groups: list[dict[str, Any]] = []

    for event_index in range(250):
        start = event_index * 2 + 1
        end = start + 1
