def _write_json(path: Path, value: Any) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _validate(clusters: list[dict[str, Any]], cards: list[dict[str, Any]]) -> dict[str, Any]:
    chapter_ids = [int(x["chapter_id"]) for x in cards]
    covered = [c for cluster in clusters for c in range(cluster["chapter_span"][0], cluster["chapter_span"][1] + 1)]
    failures: list[str] = []
    if len(clusters) != 250: failures.append(f"cluster_count={len(clusters)}")
    if len(cards) != 500: failures.append(f"card_count={len(cards)}")
    if chapter_ids != list(range(1, 501)): failures.append("chapter ids are not exactly 1..500")
    if covered != list(range(1, 501)): failures.append("cluster spans do not cover exactly 1..500")
    if any(cluster["chapter_span"][1] - cluster["chapter_span"][0] + 1 != 2 for cluster in clusters): failures.append("event clusters are not exactly two chapters")
    if any(card["cluster_id"] != f"EC{(int(card['chapter_id']) + 1) // 2:03d}" for card in cards): failures.append("chapter to two-chapter event mapping mismatch")
    if any(card["cluster_chapter_total"] != 2 for card in cards): failures.append("chapter cards do not declare two-chapter events")
    if cards[1]["timeline_years"] != "2009→1969": failures.append("chapter 2 rebirth anchor missing")
    if any("未成年" not in card["romance_state"] for card in cards[:90]): failures.append("minor romance guard failed")
    required_flywheel = {"fictional_obstacle", "preemptive_avoidance", "ascension_gain", "rebirth_flywheel"}
    if any(not required_flywheel.issubset(cluster) for cluster in clusters): failures.append("rebirth flywheel fields missing")
    if any(len(cluster["chapter_milestones"]) != 2 for cluster in clusters): failures.append("two-chapter milestone count failed")
    if any("两章一事" not in cluster["summary"] for cluster in clusters): failures.append("two-chapter event summary guard failed")
    return {"ok": not failures, "failures": failures, "cluster_count": len(clusters), "chapter_card_count": len(cards), "covered_chapters": [min(covered), max(covered)]}


